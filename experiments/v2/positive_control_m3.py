r"""Positive control against M3 used as documented (review finding 2, round-3 corrected).

WHAT THIS DOES AND DOES NOT ESTABLISH
-------------------------------------
Round 2 used M3 only to obtain a measurement map and then called OUR `apply_rem` for
both outputs. That supported a claim about *mapping agreement*, not about independent
mitigation, yet the text implied the latter. Round 3 adds a genuine M3 correction:
the true per-physical-qubit response matrices are injected with
`M3Mitigation.cals_from_matrices`, and `M3.apply_correction` performs the correction
using the qubit list derived from M3's own `final_measurement_mapping`.

Two independent checks are now reported separately and labelled as such:
  (A) MAPPING AGREEMENT  - M3's `final_measurement_mapping` vs our `measurement_map`.
  (B) CORRECTION CONTROL - M3's own correction recovers the ideal distribution, and
      fails when given the virtual-qubit list instead.

The noisy input is generated by `ordering.apply_readout_bitwise`, a code path
independent of both M3's solver and our tensored inversion.

We do NOT claim any released library is defective. The failing configuration is our
own earlier virtual-index integration, reproduced deliberately.
"""
from __future__ import annotations
import os, json, pathlib, sys
for v in ("OMP_NUM_THREADS","OPENBLAS_NUM_THREADS","MKL_NUM_THREADS"): os.environ.setdefault(v,"1")
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT/"src"))
from qiskit import QuantumCircuit, transpile
from qiskit.quantum_info import Statevector
from qemstudy.v2.circuits import measurement_map, BASIS_GATES
from qemstudy.v2.ordering import phys_to_clbit_probs, apply_readout_bitwise
from qemstudy.v2.rem import apply_rem
import mthree
from mthree.utils import final_measurement_mapping

OUT = ROOT/"supplementary"/"positive_control_m3.md"
N = 4
P_ERR = {0: 0.30, 1: 0.02, 2: 0.15, 3: 0.05}
LINE = [[0,1],[1,2],[2,3],[1,0],[2,1],[3,2]]
SHOTS = 10**7          # large, so discretisation rather than sampling limits accuracy


def resp(p): return np.array([[1-p, p], [p, 1-p]])
def mats_for(order): return np.stack([resp(P_ERR[q]) for q in order])


def build(layout):
    qc = QuantumCircuit(N)
    qc.x(0); qc.ry(0.9, 2); qc.cx(2, 3); qc.rz(0.4, 1); qc.h(1)
    qc.measure_all()
    return transpile(qc, basis_gates=BASIS_GATES, coupling_map=LINE,
                     initial_layout=layout, optimization_level=1, seed_transpiler=0)


def to_vec(d):
    v = np.zeros(2**N)
    for b, val in d.items(): v[int(b, 2)] = val
    return v


rows = []
for layout in ([0,1,2,3], [3,2,1,0], [1,3,0,2], [2,0,3,1]):
    t = build(layout)
    ours = measurement_map(t)
    m3map = final_measurement_mapping(t)
    m3_clbit_to_phys = tuple(q for q, c in sorted(m3map.items(), key=lambda kv: kv[1]))
    agree = tuple(ours) == m3_clbit_to_phys

    p_phys = np.abs(Statevector.from_instruction(
        t.remove_final_measurements(inplace=False)).data) ** 2
    p_ideal = phys_to_clbit_probs(p_phys, ours)                      # correct ordering
    p_meas = apply_readout_bitwise(p_ideal, [P_ERR[ours[c]] for c in range(N)])
    counts = {format(i, f"0{N}b"): int(round(p_meas[i]*SHOTS))
              for i in range(2**N) if p_meas[i] > 1e-12}

    # (B) genuine M3 correction with injected true calibration
    mit = mthree.M3Mitigation()
    mit.cals_from_matrices([resp(P_ERR[q]) for q in range(N)])
    qubits_ok = [q for q, _ in sorted(m3map.items(), key=lambda kv: kv[1])]
    e_m3_ok = float(np.abs(to_vec(mit.apply_correction(counts, qubits_ok)) - p_ideal).max())
    e_m3_bad = float(np.abs(to_vec(mit.apply_correction(counts, list(range(N)))) - p_ideal).max())

    # ours, for comparison (tensored inversion)
    def ours_err(order):
        rec, _ = apply_rem(counts, mats_for(order), N, clip=False)
        v = np.zeros(2**N)
        for b, c in rec.items(): v[int(b, 2)] = c/SHOTS
        return float(np.abs(v - p_ideal).max())
    e_v2, e_v1 = ours_err(ours), ours_err(tuple(range(N)))

    rows.append(dict(layout=str(layout), ours=str(list(ours)), m3=str(list(m3_clbit_to_phys)),
                     agree=agree, e_m3_ok=e_m3_ok, e_m3_bad=e_m3_bad, e_v2=e_v2, e_v1=e_v1))
    print(f"layout={layout} map_agree={agree} | M3 correct={e_m3_ok:.2e} M3 virtual-index={e_m3_bad:.2e} "
          f"| ours v2={e_v2:.2e} v1={e_v1:.2e}")

L = [r"# Supplementary: positive control against M3",
     "", "Generated by `experiments/v2/positive_control_m3.py`. The noisy input is produced by an",
     "independent bitwise readout channel (`ordering.apply_readout_bitwise`, validated against Aer's",
     f"own `ReadoutError` model), discretised at {SHOTS:,} shots.",
     "", "## Scope of this control",
     "", "Two things are checked, and they are **not** the same claim:",
     "", "* **(A) mapping agreement** — does M3's `final_measurement_mapping` recover the same",
     "  clbit→physical map as ours?",
     "* **(B) correction control** — does **M3's own correction** (`apply_correction`, with the true",
     "  per-qubit matrices injected via `cals_from_matrices`) recover the ideal distribution, and does",
     "  it fail when handed the virtual-qubit list instead?",
     "",
     "An earlier version of this script performed only (A) while the text implied (B). That",
     "overstatement is corrected: (B) is now actually run.",
     "",
     f"Environment: mthree {mthree.__version__}. Per-physical-qubit readout errors are deliberately",
     "unequal: " + ", ".join(f"q{q}={p}" for q, p in P_ERR.items()) + ".",
     "", "## Result", "",
     "| `initial_layout` | our map | M3 map | (A) agree | (B) M3 correction, correct qubits | (B) M3 correction, virtual index | ours (corrected) | ours (v1 defect) |",
     "|---|---|---|---|---|---|---|---|"]
for r in rows:
    L.append(f"| `{r['layout']}` | `{r['ours']}` | `{r['m3']}` | {'yes' if r['agree'] else '**no**'} | "
             f"{r['e_m3_ok']:.1e} | {r['e_m3_bad']:.1e} | {r['e_v2']:.1e} | {r['e_v1']:.1e} |")
L += ["",
      "**Reading.** M3's mapping agrees with ours on every layout (A). M3's own correction recovers the",
      "ideal distribution when given the physical qubits it actually measured, and fails by one to two",
      "orders of magnitude when given the virtual-qubit list (B). Our corrected implementation matches;",
      "only our own earlier virtual-index integration fails. The identity layout is a degenerate case",
      "in which the defect is invisible.",
      "",
      "**What this does not show.** It does not establish that any released library is defective, and",
      "it does not validate M3 beyond this small scope: four layouts, four qubits, independent",
      "symmetric per-qubit readout error, and injected rather than measured calibration."]
OUT.write_text("\n".join(L)+"\n")
print("\nwrote", OUT)
