r"""Audit what unitary folding amplifies. Writes supplementary/noise_scaling_audit.md.

ROUND-2 CORRECTION (review finding 3)
-------------------------------------
The previous version called ``remove_final_measurements()`` and then saved the
density matrix. Readout error in Aer is applied AT MEASUREMENT, so that path never
applied the readout channel at all and reported <ZZ> = 1.000000 for a readout-only
noise model. The "exactly invariant" conclusion was therefore vacuous: it measured
a circuit with no measurement.

This version computes the measured expectation EXACTLY and without sampling:
  1. take the exact computational-basis output probabilities p from the density
     matrix of the (possibly gate-noisy) circuit;
  2. apply the explicit readout response matrix A = (x)_q A_q classically,
     p_meas = A p;
  3. evaluate <ZZ> against p_meas.
For an ideal |00> state with independent symmetric readout error p on both measured
qubits this gives (1-2p)^2 = 0.81 at p = 0.05, matching the analytic value, not 1.

The substantive conclusion (folding does not amplify readout error) survives, but the
correct statement is that the readout factor is a CONSTANT multiplicative attenuation
that does not change with the scale factor -- not that readout noise leaves the
expectation untouched.
"""
from __future__ import annotations
import os, pathlib, sys, json
for v in ("OMP_NUM_THREADS","OPENBLAS_NUM_THREADS","MKL_NUM_THREADS"): os.environ.setdefault(v,"1")
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT/"src"))
from qiskit import QuantumCircuit, transpile
from qiskit.quantum_info import DensityMatrix
from qiskit_aer import AerSimulator
from qiskit_aer.noise import NoiseModel, depolarizing_error
from qemstudy.v2.circuits import fold_preserving_measurements, to_basis, BASIS_GATES
from qemstudy.v2.instances import MaxCutInstance
from qemstudy.noise import DEVICES

OUT = ROOT/"supplementary"/"noise_scaling_audit.md"; OUT.parent.mkdir(exist_ok=True)
NQ = 4
MEAS_Q = (0, 1)            # observable ZZ on qubits 0,1


def gate_noise_model(p):
    m = NoiseModel()
    if p:
        m.add_all_qubit_quantum_error(depolarizing_error(p, 1), ["sx", "x"])
        m.add_all_qubit_quantum_error(depolarizing_error(p, 2), ["cx"])
    return m


def exact_probs(circ, noise):
    """Exact computational-basis probabilities of the unitary part (no measurement)."""
    c = circ.remove_final_measurements(inplace=False).copy()
    sim = AerSimulator(method="density_matrix", noise_model=noise, max_parallel_threads=1)
    c.save_density_matrix()
    dm = DensityMatrix(sim.run(transpile(c, sim, optimization_level=0)).result().data()["density_matrix"])
    return np.real(np.diag(dm.data))


def readout_matrix(n, p):
    """Tensored independent symmetric readout response, qubit 0 least significant."""
    A1 = np.array([[1 - p, p], [p, 1 - p]])
    A = np.array([[1.0]])
    for _ in range(n):
        A = np.kron(A1, A)        # order irrelevant for identical symmetric blocks
    return A


def zz_from_probs(probs, n, qubits):
    idx = np.arange(probs.size)
    par = np.zeros(probs.size)
    for q in qubits:
        par += ((idx >> q) & 1)
    return float(np.dot(probs, np.where(par % 2 == 0, 1.0, -1.0)))


L = [r"# Supplementary: what unitary folding amplifies",
     "",
     "Generated by `experiments/v2/noise_scaling_audit.py`. All values are **exact**: output",
     "probabilities come from the density matrix and the readout channel is applied explicitly as",
     r"$p_{\text{meas}} = A\,p$. No sampling is involved.",
     "",
     "> **Round-2 correction.** An earlier version of this audit removed the measurements before",
     "> saving the density matrix. Aer applies readout error at measurement, so that computation",
     "> never applied the readout channel and reported $\\langle ZZ\\rangle = 1.000000$ for a",
     "> readout-only model. The corrected value for independent symmetric $p=0.05$ on both measured",
     "> qubits is $(1-2p)^2 = 0.81$. The conclusion that folding does not amplify readout error",
     "> stands, but the correct statement is that readout contributes a **constant multiplicative",
     "> attenuation that does not vary with the scale factor**.",
     "",
     "## 1. Gate noise vs readout noise under folding", ""]

probe = QuantumCircuit(NQ); probe.h(0); probe.cx(0, 1); probe.cx(1, 2); probe.cx(2, 3); probe.measure_all()
pt = transpile(probe, basis_gates=BASIS_GATES, optimization_level=1, seed_transpiler=0)
scales = (1.0, 3.0, 5.0)

L += ["| noise present | $\\langle ZZ\\rangle$ at scale 1 | scale 3 | scale 5 | scale-5 / scale-1 |",
      "|---|---|---|---|---|"]
rows = {}
for label, gp, rp in [("none (reference)", 0.0, 0.0),
                      ("gate noise only (depolarising $10^{-2}$)", 1e-2, 0.0),
                      ("readout noise only ($p=0.05$)", 0.0, 0.05),
                      ("both", 1e-2, 0.05)]:
    A = readout_matrix(NQ, rp) if rp else None
    vals = []
    for s in scales:
        fc = to_basis(fold_preserving_measurements(pt, s), 0)
        p = exact_probs(fc, gate_noise_model(gp))
        if A is not None:
            p = A @ p
        vals.append(zz_from_probs(p, NQ, MEAS_Q))
    rows[label] = vals
    L.append(f"| {label} | {vals[0]:.6f} | {vals[1]:.6f} | {vals[2]:.6f} | {vals[2]/vals[0]:.4f} |")

ro_only = rows["readout noise only ($p=0.05$)"]
analytic = (1 - 2 * 0.05) ** 2
L += ["",
      f"Analytic check for the readout-only row: $(1-2p)^2 = {analytic:.6f}$ versus computed "
      f"{ro_only[0]:.6f} (agreement to {abs(ro_only[0]-analytic):.2e}).",
      "",
      "**Reading.** Readout error attenuates $\\langle ZZ\\rangle$ by a constant factor that is",
      "identical at every scale factor (scale-5/scale-1 ratio exactly 1 for the readout-only row),",
      "whereas gate noise is amplified by folding. Folding therefore cannot extrapolate readout",
      "error away, which is the point already made by Majumdar *et al.* (IEEE QCE 2023, Sec. V);",
      "this is a verification, not a new finding.",
      "",
      "## 2. Realised gate counts per scale factor", ""]

inst = MaxCutInstance.get("prism")
refs = json.loads((ROOT/"configs/v2/references.json").read_text())
qc = inst.measured_circuits(refs["prism"]["ansatz_reference_params"])["z"]
t = transpile(qc, basis_gates=BASIS_GATES, optimization_level=1, seed_transpiler=0)
base = t.count_ops()
L += [f"Base circuit (`prism`, $p=1$): " + ", ".join(f"`{g}`={base.get(g,0)}" for g in BASIS_GATES), "",
      "| nominal scale | cx | sx | x | rz | cx ratio | sx ratio | uniform over error-carrying gates? |",
      "|---|---|---|---|---|---|---|---|"]
for s in (2.0, 3.0, 4.0, 5.0):
    c = to_basis(fold_preserving_measurements(t, s), 0).count_ops()
    rc = c.get("cx", 0)/max(base.get("cx", 1), 1); rs = c.get("sx", 0)/max(base.get("sx", 1), 1)
    uni = "yes" if abs(rc-rs) < 1e-9 and abs(rc-round(rc)) < 1e-9 else "**no**"
    L.append(f"| {s:g} | {c.get('cx',0)} | {c.get('sx',0)} | {c.get('x',0)} | {c.get('rz',0)} | "
             f"{rc:.2f} | {rs:.2f} | {uni} |")
L += ["", "At **odd** scales the error-carrying gates fold a whole number of times. `rz` does not,",
      "but `rz` is error-free in every noise model used here:", ""]
for name, B in DEVICES.items():
    b = B(); m = NoiseModel.from_backend(b)
    L.append(f"- `{name}`: `noise_instructions = {sorted(m.noise_instructions)}` (no `rz`)")
L += ["", "**Caveat.** Equal gate counts are necessary but *not sufficient* for uniform effective noise",
      "scaling: coherent errors, crosstalk and idle/thermal evolution during the longer folded circuit",
      "are not captured by a count ratio. We validate ideal equivalence directly",
      "(`tests/test_v2_correctness.py`) and do not claim odd factors prove uniform scaling."]
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT)
for k, v in rows.items():
    print(f"  {k:42s} {[round(x,6) for x in v]}")
