"""Audit what unitary folding amplifies. Writes supplementary/noise_scaling_audit.md.

Exact density-matrix computation (no sampling) plus realised gate counts per scale.
Regenerates every number quoted in manuscript Sec. IV-D.
"""
from __future__ import annotations
import os, pathlib, sys, json
for v in ("OMP_NUM_THREADS","OPENBLAS_NUM_THREADS","MKL_NUM_THREADS"): os.environ.setdefault(v,"1")
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT/"src"))
from qiskit import QuantumCircuit, transpile
from qiskit.quantum_info import DensityMatrix, SparsePauliOp
from qiskit_aer import AerSimulator
from qiskit_aer.noise import NoiseModel, depolarizing_error, ReadoutError
from qemstudy.v2.circuits import fold_preserving_measurements, to_basis, BASIS_GATES
from qemstudy.v2.instances import MaxCutInstance
from qemstudy.noise import DEVICES

OUT = ROOT/"supplementary"/"noise_scaling_audit.md"; OUT.parent.mkdir(exist_ok=True)

def nm(gate_p, ro_p):
    m = NoiseModel()
    if gate_p:
        m.add_all_qubit_quantum_error(depolarizing_error(gate_p,1), ["sx","x"])
        m.add_all_qubit_quantum_error(depolarizing_error(gate_p,2), ["cx"])
    if ro_p: m.add_all_qubit_readout_error(ReadoutError([[1-ro_p,ro_p],[ro_p,1-ro_p]]))
    return m

def exact_expval(circ, noise, obs):
    c = circ.remove_final_measurements(inplace=False).copy()
    sim = AerSimulator(method="density_matrix", noise_model=noise, max_parallel_threads=1)
    c.save_density_matrix()
    dm = DensityMatrix(sim.run(transpile(c, sim, optimization_level=0)).result().data()["density_matrix"])
    return float(np.real(dm.expectation_value(obs)))

L = ["# Supplementary: what unitary folding amplifies",
     "", "Generated by `experiments/v2/noise_scaling_audit.py`. Exact density-matrix values; no sampling.",
     "", "## 1. Gate noise vs readout noise under folding", ""]
probe = QuantumCircuit(4); probe.h(0); probe.cx(0,1); probe.cx(1,2); probe.cx(2,3); probe.measure_all()
pt = transpile(probe, basis_gates=BASIS_GATES, optimization_level=1, seed_transpiler=0)
obs = SparsePauliOp.from_list([("ZZII",1.0)])
L += ["| noise present | <ZZ> at scale 1 | scale 3 | scale 5 | behaviour |","|---|---|---|---|---|"]
for label, gp, rp in [("gate noise only (depolarising 1e-2)",1e-2,0.0),
                      ("readout noise only (p=0.05)",0.0,0.05)]:
    vals=[exact_expval(to_basis(fold_preserving_measurements(pt,s),0), nm(gp,rp), obs) for s in (1.0,3.0,5.0)]
    beh = "amplified" if abs(vals[0]-vals[2])>1e-9 else "**exactly invariant**"
    L.append(f"| {label} | {vals[0]:.6f} | {vals[1]:.6f} | {vals[2]:.6f} | {beh} |")
L += ["", "Gate folding therefore cannot mitigate readout error. This confirms the point made by",
      "Majumdar *et al.* (IEEE QCE 2023, Sec. V); it is stated here as a verification, not a new finding.",
      "", "## 2. Realised gate counts per scale factor", ""]
inst = MaxCutInstance.get("prism")
refs = json.loads((ROOT/"configs/v2/references.json").read_text())
qc = inst.measured_circuits(refs["prism"]["ansatz_reference_params"])["z"]
t = transpile(qc, basis_gates=BASIS_GATES, optimization_level=1, seed_transpiler=0)
base = t.count_ops()
L += [f"Base circuit (`prism`, p=1): " + ", ".join(f"`{g}`={base.get(g,0)}" for g in BASIS_GATES), "",
      "| nominal scale | cx | sx | x | rz | cx ratio | sx ratio | uniform over error-carrying gates? |",
      "|---|---|---|---|---|---|---|---|"]
for s in (2.0,3.0,4.0,5.0):
    c = to_basis(fold_preserving_measurements(t,s),0).count_ops()
    rc = c.get("cx",0)/max(base.get("cx",1),1); rs = c.get("sx",0)/max(base.get("sx",1),1)
    uni = "yes" if abs(rc-rs) < 1e-9 and abs(rc-round(rc)) < 1e-9 else "**no**"
    L.append(f"| {s:g} | {c.get('cx',0)} | {c.get('sx',0)} | {c.get('x',0)} | {c.get('rz',0)} | "
             f"{rc:.2f} | {rs:.2f} | {uni} |")
L += ["", "At **odd** scales the error-carrying gates fold a whole number of times. `rz` does not,",
      "but `rz` is error-free in every noise model used here:", ""]
for name,B in DEVICES.items():
    b=B(); m=NoiseModel.from_backend(b)
    L.append(f"- `{name}`: `noise_instructions = {sorted(m.noise_instructions)}` (no `rz`)")
L += ["", "**Caveat.** Equal gate counts are necessary but *not sufficient* for uniform effective noise",
      "scaling: coherent errors, crosstalk, and idle/thermal evolution during the longer folded circuit",
      "are not captured by a count ratio. We therefore validate ideal equivalence directly",
      "(`tests/test_v2_correctness.py`, tests T1/T2/T5) and do not claim odd factors prove uniform scaling."]
OUT.write_text("\n".join(L)+"\n")
print("wrote", OUT)
